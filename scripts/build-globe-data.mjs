// Builds src/lib/globe-data.ts: compact country geometry for the interactive footer globe.
// Source: Natural Earth via the world-atlas package (public domain): 1:50m for West Africa and the Sahara, 1:110m elsewhere.
// Rings keep the winding d3-geo expects. Run: node scripts/build-globe-data.mjs
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const t110 = require("world-atlas/countries-110m.json"), t50 = require("world-atlas/countries-50m.json");

const CLS = { Gambia: "born", "Sierra Leone": "grew", Nigeria: "descent", Ghana: "living",
  Mali: "visited", "Burkina Faso": "visited", Guinea: "visited", Liberia: "visited", "Côte d'Ivoire": "visited", Togo: "visited", Benin: "visited" };
const centre = (f) => { let sx = 0, sy = 0, n = 0; const walk = (a) => { if (typeof a[0] === "number") { sx += a[0]; sy += a[1]; n++; } else a.forEach(walk); }; walk(f.geometry.coordinates); return [sx / n, sy / n]; };
const inWest = (f) => { const [x, y] = centre(f); return x > -20 && x < 20 && y > 0 && y < 28; };

// Douglas-Peucker in lon/lat degrees, keeping the ring closed
function simplify(pts, tol) {
  if (pts.length < 6) return pts;
  const d2 = (p, a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1]; const l = dx * dx + dy * dy || 1e-12; let t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l; t = Math.max(0, Math.min(1, t)); const x = a[0] + t * dx - p[0], y = a[1] + t * dy - p[1]; return x * x + y * y; };
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) { const [i, j] = st.pop(); let m = 0, k = -1; for (let n = i + 1; n < j; n++) { const d = d2(pts[n], pts[i], pts[j]); if (d > m) { m = d; k = n; } } if (m > tol * tol && k > 0) { keep[k] = 1; st.push([i, k], [k, j]); } }
  const o = pts.filter((_, i) => keep[i]); return o.length >= 4 ? o : pts;
}
const round = (ring, dp) => { const k = 10 ** dp, out = []; for (const [x, y] of ring) { const p = [Math.round(x * k) / k, Math.round(y * k) / k]; const l = out[out.length - 1]; if (!l || l[0] !== p[0] || l[1] !== p[1]) out.push(p); } return out; };
const clean = (rings, dp, tol) => rings.map((r) => simplify(round(r, dp), tol)).filter((r) => r.length >= 4 || (r.length === 3));
const closeRing = (r) => (r[0][0] === r[r.length - 1][0] && r[0][1] === r[r.length - 1][1] ? r : [...r, r[0]]);

const f50 = feature(t50, t50.objects.countries).features, f110 = feature(t110, t110.objects.countries).features;
const names50 = new Map(f50.map((f) => [f.properties.name, f]));
const out = [];
const seen = new Set();
for (const f of f110) {
  const name = f.properties.name;
  const hi = names50.get(name);
  const use = hi && (CLS[name] || inWest(hi)) ? hi : f;       // fine outlines where it matters
  const dp = use === hi ? 2 : 1;
  const polys = use.geometry.type === "Polygon" ? [use.geometry.coordinates] : use.geometry.coordinates;
  const g = polys.map((p) => clean(p, dp, use === hi ? (CLS[name] ? 0.025 : 0.06) : 0.12).map(closeRing)).filter((p) => p.length && p[0].length >= 4);
  if (g.length) { out.push([name, CLS[name] ?? "land", g]); seen.add(name); }
}
const ts = `/* Generated by scripts/build-globe-data.mjs from Natural Earth (public domain, via world-atlas). Do not edit by hand.
   [name, class, polygons], polygons as lon/lat rings in the winding d3-geo expects. */
export type GlobeCls = "land" | "visited" | "born" | "grew" | "descent" | "living";
export type GlobeRow = [string, GlobeCls, number[][][][]];
export const GLOBE_DATA: GlobeRow[] = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL("../src/lib/globe-data.ts", import.meta.url), ts);
console.log(out.length, "countries,", Math.round(ts.length / 1024) + " KB;", "story/visited found:", Object.keys(CLS).filter((n) => seen.has(n)).length, "of", Object.keys(CLS).length);
