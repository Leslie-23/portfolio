// Builds src/lib/africa-map.ts: simplified West Africa country outlines as SVG paths.
// Source: Natural Earth 1:50m admin-0 countries (public domain, https://www.naturalearthdata.com).
// Usage: node scripts/build-africa-map.mjs path/to/ne_50m_admin_0_countries.geojson
import fs from "node:fs";

const SRC = process.argv[2];
if (!SRC) { console.error("pass the Natural Earth geojson path"); process.exit(1); }
const W = 1000;
const BOX = { x0: -18, x1: 15.6, y0: 3.8, y1: 22 };           // lon/lat frame
const K = Math.cos(((BOX.y0 + BOX.y1) / 2) * Math.PI / 180);   // equirectangular, scaled at the middle latitude
const SC = W / ((BOX.x1 - BOX.x0) * K);
const H = Math.round((BOX.y1 - BOX.y0) * SC);
const proj = ([lon, lat]) => [(lon - BOX.x0) * K * SC, (BOX.y1 - lat) * SC];

const ISO = { GMB: "Gambia", SLE: "Sierra Leone", NGA: "Nigeria", GHA: "Ghana", MLI: "Mali", BFA: "Burkina Faso", GIN: "Guinea", LBR: "Liberia", CIV: "Ivory Coast", TGO: "Togo", BEN: "Benin",
  SEN: "Senegal", GNB: "Guinea-Bissau", MRT: "Mauritania", NER: "Niger", CMR: "Cameroon", TCD: "Chad", DZA: "Algeria" };

// Sutherland-Hodgman against the frame, in lon/lat
function clip(ring) {
  const edges = [
    [(p) => p[0] >= BOX.x0, (a, b) => { const t = (BOX.x0 - a[0]) / (b[0] - a[0]); return [BOX.x0, a[1] + t * (b[1] - a[1])]; }],
    [(p) => p[0] <= BOX.x1, (a, b) => { const t = (BOX.x1 - a[0]) / (b[0] - a[0]); return [BOX.x1, a[1] + t * (b[1] - a[1])]; }],
    [(p) => p[1] >= BOX.y0, (a, b) => { const t = (BOX.y0 - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), BOX.y0]; }],
    [(p) => p[1] <= BOX.y1, (a, b) => { const t = (BOX.y1 - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), BOX.y1]; }],
  ];
  let out = ring;
  for (const [inside, cut] of edges) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const cur = inp[i], prev = inp[(i + inp.length - 1) % inp.length];
      if (inside(cur)) { if (!inside(prev)) out.push(cut(prev, cur)); out.push(cur); } else if (inside(prev)) out.push(cut(prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}
// Douglas-Peucker
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const d2 = (p, a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1]; const l = dx * dx + dy * dy || 1e-9; let t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l; t = Math.max(0, Math.min(1, t)); const x = a[0] + t * dx - p[0], y = a[1] + t * dy - p[1]; return x * x + y * y; };
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) { const [i, j] = st.pop(); let m = 0, k = -1; for (let n = i + 1; n < j; n++) { const d = d2(pts[n], pts[i], pts[j]); if (d > m) { m = d; k = n; } } if (m > tol * tol && k > 0) { keep[k] = 1; st.push([i, k], [k, j]); } }
  return pts.filter((_, i) => keep[i]);
}
const area = (r) => { let s = 0; for (let i = 0; i < r.length; i++) { const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length]; s += x1 * y2 - x2 * y1; } return s / 2; };
const centroid = (r) => { let a = 0, cx = 0, cy = 0; for (let i = 0; i < r.length; i++) { const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length]; const f = x1 * y2 - x2 * y1; a += f; cx += (x1 + x2) * f; cy += (y1 + y2) * f; } a /= 2; return [cx / (6 * a), cy / (6 * a)]; };

const gj = JSON.parse(fs.readFileSync(SRC, "utf8"));
const out = [];
for (const f of gj.features) {
  const id = f.properties.ADM0_A3; if (!ISO[id]) continue;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = "", best = null;
  for (const poly of polys) {
    const ring = clip(poly[0]); if (ring.length < 3) continue;
    const pr = simplify(ring.map(proj), 1.1); if (pr.length < 3) continue;
    const a = Math.abs(area(pr)); if (a < 18) continue;       // drop specks
    d += "M" + pr.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z";
    if (!best || a > best.a) best = { a, c: centroid(pr) };
  }
  if (d) out.push({ id, name: ISO[id], d, cx: +best.c[0].toFixed(1), cy: +best.c[1].toFixed(1) });
}
const ts = `/* Generated by scripts/build-africa-map.mjs from Natural Earth 1:50m admin-0 countries (public domain).
   Equirectangular, ${W} x ${H}. Do not edit by hand. */
export const AFRICA_W = ${W};
export const AFRICA_H = ${H};
export type CountryShape = { id: string; name: string; d: string; cx: number; cy: number };
export const COUNTRIES: CountryShape[] = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(new URL("../src/lib/africa-map.ts", import.meta.url), ts);
console.log(out.length, "countries,", Math.round(ts.length / 1024) + " KB, viewBox", W, H);
