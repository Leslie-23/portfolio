// Builds src/lib/globe-raster.ts: a 0.5 degree world land raster, run-length encoded, with the countries that
// matter to the footer globe classified. Source: Natural Earth 1:50m admin-0 countries (public domain).
// Usage: node scripts/build-globe-raster.mjs path/to/ne_50m_admin_0_countries.geojson
import fs from "node:fs";

const SRC = process.argv[2];
if (!SRC) { console.error("pass the Natural Earth geojson path"); process.exit(1); }
const STEP = 0.5, COLS = 360 / STEP, ROWS = 180 / STEP, SUB = 3;
// o ocean, l land, then the four countries of the story, then the places visited
const CLASS = { GMB: "b", SLE: "s", NGA: "n", GHA: "g", MLI: "v", BFA: "v", GIN: "v", LBR: "v", CIV: "v", TGO: "v", BEN: "v" };
const RANK = { o: 0, l: 1, v: 2, b: 3, s: 3, n: 3, g: 3 };          // when sub-samples disagree, the more meaningful class wins

const gj = JSON.parse(fs.readFileSync(SRC, "utf8"));
const grid = new Array(ROWS * COLS).fill("o");
const inRing = (x, y, r) => { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c; } return c; };

for (const f of gj.features) {
  const cls = CLASS[f.properties.ADM0_A3] ?? "l";
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
    for (const [x, y] of poly[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    const c0 = Math.max(0, Math.floor((x0 + 180) / STEP)), c1 = Math.min(COLS - 1, Math.floor((x1 + 180) / STEP));
    const r0 = Math.max(0, Math.floor((90 - y1) / STEP)), r1 = Math.min(ROWS - 1, Math.floor((90 - y0) / STEP));
    for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) {
      let hit = false;
      for (let a = 0; a < SUB && !hit; a++) for (let b = 0; b < SUB && !hit; b++) {
        const lon = -180 + (c + (a + 0.5) / SUB) * STEP, lat = 90 - (r + (b + 0.5) / SUB) * STEP;
        if (!inRing(lon, lat, poly[0])) continue;
        let holed = false; for (let h = 1; h < poly.length; h++) if (inRing(lon, lat, poly[h])) { holed = true; break; }
        if (!holed) hit = true;
      }
      if (hit && RANK[cls] > RANK[grid[r * COLS + c]]) grid[r * COLS + c] = cls;
    }
  }
}
const rows = [];
const sums = {};
for (let r = 0; r < ROWS; r++) {
  let s = "", cur = grid[r * COLS], n = 0;
  for (let c = 0; c < COLS; c++) {
    const k = grid[r * COLS + c];
    if (k !== "o" && k !== "l" && k !== "v") { const t = (sums[k] ??= { lon: 0, lat: 0, n: 0 }); t.lon += -180 + (c + 0.5) * STEP; t.lat += 90 - (r + 0.5) * STEP; t.n++; }
    if (k === cur) n++; else { s += cur + n; cur = k; n = 1; }
  }
  rows.push(s + cur + n);
}
const centers = Object.fromEntries(Object.entries(sums).map(([k, t]) => [k, [+(t.lon / t.n).toFixed(2), +(t.lat / t.n).toFixed(2)]]));
const counts = Object.fromEntries(Object.entries(sums).map(([k, t]) => [k, t.n]));
const ts = `/* Generated by scripts/build-globe-raster.mjs from Natural Earth 1:50m admin-0 countries (public domain). Do not edit by hand.
   ${COLS} x ${ROWS} cells of ${STEP} degrees, one string per row from 90N, run-length encoded as <class><count>.
   Classes: o ocean, l land, b Gambia, s Sierra Leone, n Nigeria, g Ghana, v visited. */
export const STEP = ${STEP};
export const CENTERS: Record<string, [number, number]> = ${JSON.stringify(centers)};
export const ROWS_RLE: string[] = ${JSON.stringify(rows)};
`;
fs.writeFileSync(new URL("../src/lib/globe-raster.ts", import.meta.url), ts);
console.log("cells per class:", counts, "centres:", centers, Math.round(ts.length / 1024) + " KB");
