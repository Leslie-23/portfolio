// Builds src/lib/globe-art.ts: country outlines and a graticule in orthographic projection, as SVG paths, for the footer globe.
// Source: Natural Earth 1:50m admin-0 countries (public domain, https://www.naturalearthdata.com).
// Usage: node scripts/build-globe.mjs path/to/ne_50m_admin_0_countries.geojson
import fs from "node:fs";

const SRC = process.argv[2];
if (!SRC) { console.error("pass the Natural Earth geojson path"); process.exit(1); }
const LON0 = -2, LAT0 = 8;               // the globe is turned to face here
const C = 500, R = 470;                  // centre and radius in a 1000 x 1000 box
const D = Math.PI / 180;
const CLS = { GMB: "born", SLE: "grew", NGA: "descent", GHA: "living", MLI: "visited", BFA: "visited", GIN: "visited", LBR: "visited", CIV: "visited", TGO: "visited", BEN: "visited" };

const s0 = Math.sin(LAT0 * D), c0 = Math.cos(LAT0 * D);
function project(lon, lat) {
  const l = (lon - LON0) * D, p = lat * D;
  const x = Math.cos(p) * Math.sin(l), y = c0 * Math.sin(p) - s0 * Math.cos(p) * Math.cos(l), z = s0 * Math.sin(p) + c0 * Math.cos(p) * Math.cos(l);
  return { x, y, z };
}
const toXY = ({ x, y, z }) => {
  if (z >= 0) return [C + x * R, C - y * R];
  const m = Math.hypot(x, y) || 1;                       // behind the globe: pin to the edge
  return [C + (x / m) * R, C - (y / m) * R];
};
const unwrap = (ring) => { const out = [ring[0].slice()]; for (let i = 1; i < ring.length; i++) { let [lo, la] = ring[i]; const pl = out[i - 1][0]; while (lo - pl > 180) lo -= 360; while (lo - pl < -180) lo += 360; out.push([lo, la]); } return out; };
const densify = (ring, max) => { const out = []; for (let i = 0; i < ring.length; i++) { const a = ring[i], b = ring[(i + 1) % ring.length]; const n = Math.max(1, Math.ceil(Math.max(Math.abs(b[0] - a[0]), Math.abs(b[1] - a[1])) / max)); for (let k = 0; k < n; k++) out.push([a[0] + ((b[0] - a[0]) * k) / n, a[1] + ((b[1] - a[1]) * k) / n]); } return out; };
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const d2 = (p, a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1]; const l = dx * dx + dy * dy || 1e-9; let t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l; t = Math.max(0, Math.min(1, t)); const x = a[0] + t * dx - p[0], y = a[1] + t * dy - p[1]; return x * x + y * y; };
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) { const [i, j] = st.pop(); let m = 0, k = -1; for (let n = i + 1; n < j; n++) { const d = d2(pts[n], pts[i], pts[j]); if (d > m) { m = d; k = n; } } if (m > tol * tol && k > 0) { keep[k] = 1; st.push([i, k], [k, j]); } }
  return pts.filter((_, i) => keep[i]);
}
const fmt = (pts) => "M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z";

const gj = JSON.parse(fs.readFileSync(SRC, "utf8"));
const land = [];
for (const f of gj.features) {
  const id = f.properties.ADM0_A3, cls = CLS[id] ?? "land";
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = "";
  for (const poly of polys) {
    const outer = densify(unwrap(poly[0]), cls === "land" ? 2 : 0.6);
    const proj = outer.map(([lo, la]) => project(lo, la));
    if (!proj.some((p) => p.z > 0)) continue;             // wholly on the far side
    const pts = simplify(proj.map(toXY), cls === "land" ? 1.7 : 0.6);
    if (pts.length < 3) continue;
    if (cls === "land") { const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]); if (Math.max(...xs) - Math.min(...xs) < 9 && Math.max(...ys) - Math.min(...ys) < 9) continue; }   // specks
    d += fmt(pts);
  }
  if (d) land.push({ id, cls, d });
}
// graticule every 15 degrees, only the visible runs
const grat = [];
const run = (pts) => { let cur = []; for (const [lo, la] of pts) { const p = project(lo, la); if (p.z > 0.001) cur.push(toXY(p)); else { if (cur.length > 1) grat.push("M" + simplify(cur, 0.6).map(([x, y]) => `${x.toFixed(0)} ${y.toFixed(0)}`).join("L")); cur = []; } } if (cur.length > 1) grat.push("M" + simplify(cur, 0.6).map(([x, y]) => `${x.toFixed(0)} ${y.toFixed(0)}`).join("L")); };
for (let lo = -180; lo < 180; lo += 15) run(Array.from({ length: 91 }, (_, i) => [lo, -90 + i * 2]));
for (let la = -75; la <= 75; la += 15) run(Array.from({ length: 181 }, (_, i) => [-180 + i * 2, la]));

const order = { land: 0, visited: 1, born: 2, grew: 2, descent: 2, living: 3 };
land.sort((a, b) => order[a.cls] - order[b.cls]);
const ts = `/* Generated by scripts/build-globe.mjs from Natural Earth 1:50m admin-0 countries (public domain). Do not edit by hand.
   Orthographic projection turned to ${LON0}E ${LAT0}N, in a 1000 x 1000 box. */
export const GLOBE = { cx: ${C}, cy: ${C}, r: ${R} };
export type GlobeCountry = { id: string; cls: "land" | "visited" | "born" | "grew" | "descent" | "living"; d: string };
export const GLOBE_LAND: GlobeCountry[] = ${JSON.stringify(land)};
export const GLOBE_GRID = ${JSON.stringify(grat.join(""))};
`;
fs.writeFileSync(new URL("../src/lib/globe-art.ts", import.meta.url), ts);
console.log(land.length, "countries,", Math.round(ts.length / 1024) + " KB");
